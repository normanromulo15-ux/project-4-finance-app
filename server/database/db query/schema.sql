-- CREATE A TABLE FOR USERS
CREATE TABLE users (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  last_name TEXT NOT NULL,
  first_name TEXT NOT NULL,
  birth_date DATE NOT NULL,
  password VARCHAR(255) NOT NULL CHECK (LENGTH(password) >= 8),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)

-- CREATE A TABLE FOR ACCOUNTS
CREATE TABLE accounts (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  account VARCHAR(20) NOT NULL,
  balance NUMERIC (11,2) NOT NULL CHECK (balance >= 0),
  updated_at TIMESTAMPTZ NOT NULL
);

-- CREATE A TABLE FOR TRANSACTIONS
CREATE TABLE transactions (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  reference_id TEXT NOT NULL UNIQUE,
  account VARCHAR(20) NOT NULL,
  type VARCHAR(20) NOT NULL,
  amount NUMERIC(11, 2) NOT NULL CHECK (amount > 0),
  description VARCHAR(50) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)

-- CREATE A TABLE FOR TRANSACTION CATEGORIES
CREATE TABLE transaction_categories(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT REFERENCES transactions(id) ON DELETE CASCADE NOT NULL,
  category VARCHAR(20) NOT NULL,
  hex_color CHAR(7) NOT NULL
)

-- CREATE A TABLE FOR FUND TRANSFERS
CREATE TABLE fund_transfers (
  id BIGINT GENERATED AS ALWAYS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  reference_id TEXT NOT NULL UNIQUE,
  origin_account VARCHAR(20) NOT NULL,
  destination_account VARCHAR(20) NOT NULL,
  amount NUMERIC(11,2) NOT NULL CHECK (amount > 0),
  transfer_fee NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (transfer_fee >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
)

-- CREATE A TABLE FOR REFRESH TOKENS
CREATE TABLE refresh_tokens(
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, 
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  token TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL
)